/**
 * Entity: версия шаблона PDF-договора аренды скутера.
 *
 * На каждый тип договора (UNLIMITED / LIMITED) пользователь может создать
 * неограниченно версий. Только ОДНА версия каждого типа помечена
 * [isActive] = true — именно её использует [com.example.ui.PdfContractGenerator]
 * при генерации PDF существующими кнопками в карточке арендатора / контракта.
 *
 * Содержимое шаблона (8 реквизитов арендодателя + тело договора с
 * плейсхолдерами) сериализуется в JSON и хранится в колонке [contentJson]
 * (см. [TemplateContent]).
 *
 * Поддерживается soft-delete (isDeleted/deletedAt) — по образцу всех
 * основных таблиц v36, чтобы работала trash-мода в универсальных кнопках
 * верхнего бара MainActivity.
 *
 * @see TemplateContent
 * @see ContractTemplateDao
 * @see ContractTemplateRepository
 */
@Entity(
    tableName = "contract_templates",
    // Room's schema validation requires the entity to declare all indices that
    // exist in the actual DB. MIGRATION_36_37 creates index
    // `index_contract_templates_type_isActive` for fast lookup of active
    // templates by type — without this declaration, Room throws
    // IllegalStateException "Migration didn't properly handle" on launch
    // (expected indices={}, found the index).
    indices = [
        Index(value = ["type", "isActive"], name = "index_contract_templates_type_isActive")
    ]
)
data class ContractTemplate(
    @PrimaryKey(autoGenerate = true) val id: Int = 0,
    /** Тип договора: [TYPE_UNLIMITED] или [TYPE_LIMITED]. */
    val type: String,
    /** Имя версии, напр. «Базовый шаблон», «Версия 2 — смена банка». */
    val name: String,
    /** JSON-сериализованный [TemplateContent]. */
    val contentJson: String,
    /** true — это АКТИВНАЯ версия для своего type. Только одна на type. */
    val isActive: Boolean = false,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long? = null,
    // Soft-delete (по образцу всех сущностей v36+)
    val isDeleted: Boolean = false,
    val deletedAt: Long? = null,
    /**
     * Краткое примечание пользователя к версии (что изменено, зачем, и т.д.).
     * Добавлено в v38 (миграция 37→38). Nullable — у старых версий нет
     * примечания, отображается как пустое.
     */
    val notes: String? = null
) {
    companion object {
        /** Бесконечная аренда → [com.example.ui.PdfContractGenerator.generateUnlimited]. */
        const val TYPE_UNLIMITED = "UNLIMITED"

        /** Конечная аренда (на неделю) → [com.example.ui.PdfContractGenerator.generate]. */
        const val TYPE_LIMITED = "LIMITED"
    }
}

